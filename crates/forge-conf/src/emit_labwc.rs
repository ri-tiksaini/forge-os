#![forbid(unsafe_code)]

use crate::keymap::{Action, Bind, Keymap};

fn labwc_key(bind: &Bind) -> String {
    let mut parts: Vec<&str> = bind
        .mods
        .iter()
        .map(|m| match m.as_str() {
            "Super" => "W",
            "Shift" => "S",
            "Ctrl" => "C",
            "Alt" => "A",
            other => other,
        })
        .collect();
    parts.push(bind.key.as_str());
    parts.join("-")
}

fn labwc_action(action: &Action) -> String {
    match action {
        Action::Launcher => {
            r#"<action name="Execute" command="forge-toggle launcher" />"#.to_string()
        }
        Action::Terminal => r#"<action name="Execute" command="foot" />"#.to_string(),
        Action::Files => r#"<action name="Execute" command="thunar" />"#.to_string(),
        Action::Browser => r#"<action name="Execute" command="firefox-esr" />"#.to_string(),
        Action::CloseWindow => r#"<action name="Close" />"#.to_string(),
        Action::Fullscreen => r#"<action name="ToggleFullscreen" />"#.to_string(),
        Action::FloatToggle => r#"<action name="ToggleMaximize" />"#.to_string(),
        Action::TileToggle => r#"<action name="SnapToEdge" direction="left" />"#.to_string(),
        Action::NextWindow => r#"<action name="NextWindow" />"#.to_string(),
        Action::FocusLeft => r#"<action name="PreviousWindow" />"#.to_string(),
        Action::FocusRight => r#"<action name="NextWindow" />"#.to_string(),
        Action::Screenshot => r#"<action name="Execute" command="forge-screenshot" />"#.to_string(),
        Action::Lock => r#"<action name="Execute" command="swaylock -f -c 070709" />"#.to_string(),
        Action::Logout => r#"<action name="Execute" command="forge-toggle power" />"#.to_string(),
        Action::Workspace(n) => format!(r#"<action name="GoToDesktop" to="{n}" />"#),
        Action::MoveToWorkspace(n) => {
            format!(r#"<action name="SendToDesktop" to="{n}" follow="yes" />"#)
        }
    }
}

pub fn emit_rc_xml(keymap: &Keymap) -> String {
    let mut out = String::new();
    out.push_str("<?xml version=\"1.0\"?>\n");
    out.push_str("<!-- Auto-generated by forge-conf: Windows-style titlebars, mouse drag/resize & Dark Cherry theme. -->\n");
    out.push_str("<openbox_config xmlns=\"http://openbox.org/3.4/rc\">\n");
    out.push_str("  <core>\n");
    out.push_str("    <decoration>server</decoration>\n");
    out.push_str("  </core>\n");
    out.push_str("  <desktops>\n");
    out.push_str("    <number>9</number>\n");
    out.push_str("  </desktops>\n");
    out.push_str("  <placement>\n");
    out.push_str("    <policy>center</policy>\n");
    out.push_str("  </placement>\n");
    out.push_str("  <theme>\n");
    out.push_str("    <name>Forge-Cherry</name>\n");
    out.push_str("    <cornerRadius>10</cornerRadius>\n");
    out.push_str("    <titlebarLayout>icon:iconify,maximize,close</titlebarLayout>\n");
    out.push_str(&format!(
        "    <font place=\"ActiveWindow\"><name>{}</name><size>10</size></font>\n",
        forge_brand::FONT_UI
    ));
    out.push_str("  </theme>\n");
    out.push_str("  <windowRules>\n");
    out.push_str("    <windowRule identifier=\"org.forge.shell.launcher\" serverDecoration=\"no\" skipTaskbar=\"yes\" skipPager=\"yes\" />\n");
    out.push_str("    <windowRule identifier=\"org.forge.shell.quick\" serverDecoration=\"no\" skipTaskbar=\"yes\" skipPager=\"yes\" />\n");
    out.push_str("    <windowRule identifier=\"org.forge.shell.power\" serverDecoration=\"no\" skipTaskbar=\"yes\" skipPager=\"yes\" />\n");
    out.push_str("    <windowRule identifier=\"org.forge.shell.menu\" serverDecoration=\"no\" skipTaskbar=\"yes\" skipPager=\"yes\" />\n");
    out.push_str("  </windowRules>\n");
    // Full Windows-familiar mouse bindings: drag titlebar, resize borders, _ [] X buttons, desktop right-click
    out.push_str("  <mouse>\n");
    out.push_str("    <default />\n");
    out.push_str("    <context name=\"Titlebar\">\n");
    out.push_str(
        "      <mousebind button=\"Left\" action=\"Drag\"><action name=\"Move\" /></mousebind>\n",
    );
    out.push_str("      <mousebind button=\"Left\" action=\"DoubleClick\"><action name=\"ToggleMaximize\" /></mousebind>\n");
    out.push_str("    </context>\n");
    out.push_str("    <context name=\"Frame\">\n");
    out.push_str(
        "      <mousebind button=\"W-Left\" action=\"Drag\"><action name=\"Move\" /></mousebind>\n",
    );
    out.push_str("      <mousebind button=\"W-Right\" action=\"Drag\"><action name=\"Resize\" /></mousebind>\n");
    out.push_str("    </context>\n");
    out.push_str("    <context name=\"Root\">\n");
    out.push_str("      <mousebind button=\"Right\" action=\"Press\"><action name=\"Execute\" command=\"forge-toggle menu\" /></mousebind>\n");
    out.push_str("    </context>\n");
    out.push_str("  </mouse>\n");
    out.push_str("  <keyboard>\n");
    out.push_str("    <keybind key=\"W-i\"><action name=\"Execute\" command=\"forge-settings\" /></keybind>\n");
    out.push_str(
        "    <keybind key=\"W-n\"><action name=\"Execute\" command=\"mousepad\" /></keybind>\n",
    );
    out.push_str("    <keybind key=\"W-a\"><action name=\"Execute\" command=\"forge-toggle quick\" /></keybind>\n");
    out.push_str("    <keybind key=\"W-v\"><action name=\"Execute\" command=\"forge-clipboard\" /></keybind>\n");
    out.push_str("    <keybind key=\"Super_L\"><action name=\"Execute\" command=\"forge-toggle launcher\" /></keybind>\n");
    for bind in &keymap.binds {
        out.push_str(&format!(
            "    <keybind key=\"{}\">\n      {}\n    </keybind>\n",
            labwc_key(bind),
            labwc_action(&bind.action)
        ));
    }
    out.push_str("  </keyboard>\n");
    out.push_str("</openbox_config>\n");
    out
}

pub fn emit_autostart() -> String {
    format!(
        "#!/bin/sh\n\
         # Auto-generated by forge-conf for {} (labwc + pinned Waybar + Windows UX)\n\
         export GSK_RENDERER=cairo\n\
         export GTK_THEME=Adwaita:dark\n\
         if [ -f /usr/share/forge/wallpaper/forge-cherry.png ]; then\n\
             swaybg -i /usr/share/forge/wallpaper/forge-cherry.png -m fill >/dev/null 2>&1 &\n\
         else\n\
             swaybg -c '{}' >/dev/null 2>&1 &\n\
         fi\n\
         waybar -c /usr/share/forge/waybar/config -s /usr/share/forge/waybar/style.css >/dev/null 2>&1 &\n\
         mako >/dev/null 2>&1 &\n\
         forge-clip-watch >/dev/null 2>&1 &\n\
         swayidle -w timeout 600 'swaylock -f -c 070709' >/dev/null 2>&1 &\n\
         (sleep 0.5 && foot -e /usr/local/bin/forge-welcome-term) >/dev/null 2>&1 &\n",
        forge_brand::NAME,
        forge_brand::BG
    )
}

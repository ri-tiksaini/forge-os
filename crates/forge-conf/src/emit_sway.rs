#![forbid(unsafe_code)]

use crate::keymap::{Action, Bind, Keymap};

fn sway_key(bind: &Bind) -> String {
    let mut parts: Vec<&str> = bind
        .mods
        .iter()
        .map(|m| match m.as_str() {
            "Super" => "Mod4",
            "Shift" => "Shift",
            "Ctrl" => "Control",
            "Alt" => "Mod1",
            other => other,
        })
        .collect();
    parts.push(bind.key.as_str());
    parts.join("+")
}

fn sway_action(action: &Action) -> String {
    match action {
        Action::Launcher => {
            "exec sh -c \"pkill -f 'forge-shell --mode launcher' || forge-shell --mode launcher\""
                .to_string()
        }
        Action::Terminal => "exec foot".to_string(),
        Action::Files => "exec thunar".to_string(),
        Action::Browser => "exec firefox-esr".to_string(),
        Action::CloseWindow => "kill".to_string(),
        Action::Fullscreen => "fullscreen toggle".to_string(),
        Action::FloatToggle => "floating toggle".to_string(),
        Action::TileToggle => "layout toggle split tabbed".to_string(),
        Action::NextWindow => "focus next".to_string(),
        Action::FocusLeft => "focus left".to_string(),
        Action::FocusRight => "focus right".to_string(),
        Action::Screenshot => r#"exec sh -c 'grim -g "$(slurp)" - | wl-copy'"#.to_string(),
        Action::Lock => "exec swaylock -f -c 070709".to_string(),
        Action::Logout => {
            "exec sh -c \"pkill -f 'forge-shell --mode power' || forge-shell --mode power\""
                .to_string()
        }
        Action::Workspace(n) => format!("workspace number {n}"),
        Action::MoveToWorkspace(n) => format!("move container to workspace number {n}"),
    }
}

pub fn emit_config(keymap: &Keymap) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "# Auto-generated by forge-conf for {} — Dark Cherry Cyber HUD.\n",
        forge_brand::NAME
    ));
    out.push_str(&format!("font pango:{} 10\n", forge_brand::FONT_UI));
    out.push_str("output * bg /usr/share/forge/wallpaper/forge-cherry.png fill\n");
    out.push_str("gaps inner 8\n");
    out.push_str("gaps outer 6\n");
    out.push_str("default_border normal 2\n");
    out.push_str("default_floating_border normal 2\n");
    out.push_str("titlebar_padding 8 4\n");
    out.push_str("titlebar_border_thickness 1\n");
    // Mouse window movement & resizing: hold Win + Left-drag to move, Win + Right-drag to resize
    out.push_str("floating_modifier Mod4 normal\n");
    out.push_str("focus_follows_mouse yes\n");
    out.push_str(&format!(
        "client.focused {a} #121217 {f} #C42B42 {a}\n\
         client.unfocused #26161A #070709 #8E8E98 #26161A #26161A\n\
         client.focused_inactive #3A1018 #070709 #D4D4D8 #3A1018 #3A1018\n\n",
        a = forge_brand::ACCENT,
        f = forge_brand::FG
    ));

    // Floating rules for popups (borderless, auto-centered)
    out.push_str("for_window [app_id=\"org.forge.shell.launcher\"] floating enable, border none, move position center\n");
    out.push_str("for_window [app_id=\"org.forge.shell.power\"] floating enable, border none, move position center\n");
    out.push_str("for_window [app_id=\"org.forge.shell.quick\"] floating enable, border none, move position center\n");
    out.push_str("for_window [app_id=\"org.forge.shell.menu\"] floating enable, border none, move position center\n");
    out.push_str("for_window [app_id=\"org.forge.settings\"] floating enable, resize set 860 540, move position center\n\n");

    // Shortcuts
    out.push_str("bindsym Mod4+i exec forge-settings\n");
    out.push_str("bindsym Mod4+n exec mousepad\n");
    out.push_str("bindsym Mod4+a exec sh -c \"pkill -f 'forge-shell --mode quick' || forge-shell --mode quick\"\n");
    out.push_str("bindsym --whole-window Mod4+button3 exec sh -c \"pkill -f 'forge-shell --mode menu' || forge-shell --mode menu\"\n");
    // Keyboard resize shortcuts (smooth 40px steps)
    out.push_str("bindsym Mod4+Ctrl+Left resize shrink width 40px\n");
    out.push_str("bindsym Mod4+Ctrl+Right resize grow width 40px\n");
    out.push_str("bindsym Mod4+Ctrl+Up resize shrink height 40px\n");
    out.push_str("bindsym Mod4+Ctrl+Down resize grow height 40px\n");
    for bind in &keymap.binds {
        out.push_str(&format!(
            "bindsym {} {}\n",
            sway_key(bind),
            sway_action(&bind.action)
        ));
    }

    out.push_str(
        "\nexec waybar -c /usr/share/forge/waybar/config -s /usr/share/forge/waybar/style.css\n\
         exec mako\n\
         exec sh -c 'sleep 0.4; swaymsg \"exec foot -e /usr/local/bin/forge-welcome-term\"; sleep 0.6; swaymsg \"split h; exec foot -e /usr/local/bin/forge-hud\"; sleep 0.6; swaymsg \"split v; exec mousepad\"'\n",
    );
    out
}
